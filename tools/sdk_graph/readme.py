"""The directory tables in README.md and skill/SKILL.md, generated from site/data/graph.json between marker comments.

    python -m tools.sdk_graph readme      # rewrite the blocks; tests/test_sdk_graph.py fails when they are stale

WHY generated (Zach, 2026-11-24: "robot-sdk doesn't need to maintain that information itself. each package can
basically like define how it relates to the other packages"): every cell is a field of a package's or agent's own
robot-sdk.toml, copied through graph.json. Change the declaration, rebuild the graph, rerun this; never edit a block.
"""

from __future__ import annotations

import pathlib
import re

from . import declaration as decl
from . import languages

LINK_ORDER = ("github", "site", "docs", "pypi")
LINK_LABEL = {"github": "GitHub", "pypi": "PyPI"}
NOTE = "generated by `python -m tools.sdk_graph readme` from site/data/graph.json; edit each repo's robot-sdk.toml"


def cell(text: str | None) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def link_list(links: dict[str, str]) -> str:
    keys = [k for k in LINK_ORDER if k in links] + [k for k in links if k not in LINK_ORDER]
    return " · ".join(f"[{LINK_LABEL.get(k, k)}]({links[k]})" for k in keys)


def languages_cell(package: dict) -> str:
    """Py, C++ · partial: the landing page's chips as text (2026-11-25; a graph from before then has none)."""
    return ", ".join(languages.label(entry) for entry in package.get("languages") or [])


def by_layer(graph: dict) -> list[dict]:
    rank = {layer: i for i, layer in enumerate(decl.LAYERS)}
    return sorted(graph["packages"], key=lambda p: rank.get(p["layer"], len(rank)))  # stable: pin order inside a layer


def packages_table(graph: dict) -> str:
    rows = ["| Layer | Package (PyPI) | Repo | What it is | Languages | Links |", "|---|---|---|---|---|---|"]
    rows += [f"| {p['layer']} | `{p['pypi']}` | `../{p['id']}` | {cell(p['one_line'])} | {languages_cell(p)} | "
             f"{link_list(p['links'])} |" for p in by_layer(graph)]  # fmt: skip
    return "\n".join(rows)


def agents_table(graph: dict) -> str:
    pypi = {p["id"]: p["pypi"] for p in graph["packages"]}
    rows = ["| Agent | Repo | Objective | Builds on | Links |", "|---|---|---|---|---|"]
    for a in graph["agents"]:
        builds = ", ".join(f"`{pypi.get(b, b)}`" for b in a["builds_on"])
        rows.append(f"| {cell(a['name'])} | `../{a['id']}` | {cell(a['objective'])} | {builds} | {link_list(a['links'])} |")
    return "\n".join(rows)


def skill_table(graph: dict) -> str:
    rows = ["| Package (repo) | Languages | What it is | Reach for it when |", "|---|---|---|---|"]
    for p in by_layer(graph):
        same = p["pypi"].lower().replace("-", "_") == p["id"]
        name = f"**{p['id']}**" + ("" if same else f" (PyPI `{p['pypi']}`)")
        rows.append(f"| {name} | {languages_cell(p)} | {cell(p['summary'] or p['one_line'])} | {cell(p['use_when'])} |")
    return "\n".join(rows)


BLOCKS = {  # file (relative to robot_sdk) → [(block name, table maker)]
    "README.md": [("packages", packages_table), ("agents", agents_table)],
    "skill/SKILL.md": [("packages", skill_table)],
}


def pattern(name: str) -> re.Pattern:
    return re.compile(rf"(<!-- robot-sdk:{name} begin[^>]*-->\n)(.*?)(<!-- robot-sdk:{name} end -->)", re.S)


def render(text: str, graph: dict, blocks: list) -> str:
    for name, make in blocks:
        found = pattern(name).search(text)
        if not found:
            raise ValueError(f"no <!-- robot-sdk:{name} begin --> … <!-- robot-sdk:{name} end --> block")
        text = text[: found.start()] + f"<!-- robot-sdk:{name} begin ({NOTE}) -->\n{make(graph)}\n{found.group(3)}" + \
            text[found.end():]  # fmt: skip
    return text


def stale(sdk: pathlib.Path, graph: dict) -> list[str]:
    """Files whose generated blocks don't match graph.json."""
    out = []
    for relative, blocks in BLOCKS.items():
        text = (sdk / relative).read_text(encoding="utf-8")
        if render(text, graph, blocks) != text:
            out.append(relative)
    return out


def write(sdk: pathlib.Path, graph: dict) -> list[str]:
    changed = []
    for relative, blocks in BLOCKS.items():
        path = sdk / relative
        text = path.read_text(encoding="utf-8")
        new = render(text, graph, blocks)
        if new != text:
            path.write_text(new, encoding="utf-8")
            changed.append(relative)
    return changed
