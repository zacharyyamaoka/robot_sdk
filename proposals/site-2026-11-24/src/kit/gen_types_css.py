"""Regenerate types.v2.css: round-1 V2's Types-tab rules from src/v2/v2.css, every selector scoped under .k-types.

    python3 /home/bam/robot_sdk/proposals/site-2026-11-24/src/kit/gen_types_css.py

WHY a scoped copy and not `import "../v2/v2.css"`: v2.css styles body, button and generic names (.app, .tab, .page,
.chip, .rows …) that would leak into every round-2 variant's own shell. The switchboard's JSX is imported unchanged.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE.parent / "v2" / "v2.css").read_text()
blocks = [src[src.index("/* chips */"):src.index("/* ---------- Packages tab")],
          src[src.index(".react-flow__attribution {"):src.index("/* directory (g5)")],
          ".rows-pkg-name { border: 0; background: none; padding: 0; cursor: pointer; }\n"
          ".rows-pkg-name:hover code { background: var(--accent-soft); }\n.rows-links { margin: 4px 0 2px; }\n"]


def scope(css: str) -> str:
    out = []
    for m in re.finditer(r"(/\*.*?\*/)|([^{}]+)\{([^{}]*)\}", css, re.S):
        if m.group(1):
            out.append(m.group(1))
            continue
        sels = [".k-types " + s.strip() for s in m.group(2).split(",") if s.strip()]
        out.append(", ".join(sels) + " {" + m.group(3) + "}")
    return "\n".join(out)


header = """/* GENERATED by gen_types_css.py from src/v2/v2.css (round-1 V2 "Type Switchboard"): the rules its TypesTab needs,
   every selector scoped under .k-types so V2's generic names (.chip, .rail, .rows …) never leak into a variant's shell.
   Regenerate rather than edit: the switchboard itself is imported unchanged from src/v2/types-tab.jsx. */
"""
(HERE / "types.v2.css").write_text(header + "\n".join(scope(b) for b in blocks) + "\n")
print("wrote", HERE / "types.v2.css")
